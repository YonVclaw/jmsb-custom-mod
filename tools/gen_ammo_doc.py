#!/usr/bin/env python3
"""Write docs/AMMO_VANILLA.md - every base game ammo class and its numbers.

    python tools/gen_ammo_doc.py

Reads work/vanilla_ammo.json (built by tools/gen_vanilla_ammo.py) and renders it
grouped by what the round is, because a flat list of four hundred classnames is
a search box, not a reference.

VALUES ARE RESOLVED, NOT DECLARED. B_556x45_Ball_Tracer_Red declares a tracer
colour and gets everything else from B_556x45_Ball, so the table shows what the
round actually does rather than the two lines its own class happens to carry.
"""
import io
import json
import math
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "work", "vanilla_ammo.json")
OUT = os.path.join(ROOT, "docs", "AMMO_VANILLA.md")

# Ordered: the first pattern that matches wins, so put the specific ones first.
GROUPS = [
    ("Submunitions and penetrators", r"^ammo_"),
    ("Rifle and MG bullets", r"^[BOI]_\d|^B_\d|^SubmunitionBullet"),
    ("Shotgun", r"^B_12Gauge|Pellet"),
    ("Cannon and autocannon shells", r"^Sh_\d|^B_\d+mm|^Sh_[0-9]"),
    ("Mortar and artillery", r"^Sh_(82|120|155|Mo)|Mo_shells|^Sh_1"),
    ("Rockets", r"^R_"),
    ("Missiles", r"^M_"),
    ("Grenades - hand and UGL", r"^G_|Grenade"),
    ("Bombs", r"^Bo_"),
    ("Mines and charges", r"^(APERS|ATMine|SLAM|DemoCharge|SatchelCharge|IED)"),
    ("Flares and smoke", r"(Flare|Smoke|Chemlight)"),
    ("Everything else", r".")
]

COLS = [
    ("hit", "hit"),
    ("indirectHit", "indHit"),
    ("indirectHitRange", "indRange"),
    ("explosive", "blast"),
    ("caliber", "caliber"),
    ("_pen", "pen"),
    ("typicalSpeed", "speed"),
    ("airFriction", "drag"),
    ("_eff", "effRange"),
    ("warheadName", "warhead"),
]

# HALF THE MUZZLE VELOCITY. Arma's drag is exponential - v = v0 * e^(k*d) - so
# the distance to any fixed FRACTION of muzzle velocity depends only on k:
# ln(0.5)/k. That makes it a fair comparison between two rounds regardless of
# how fast they start, and it is why the column is the same for every load of a
# given calibre.
#
# It is DERIVED, not config. Arma has no effective-range field for a bullet, and
# a made-up one would be worse than an honest calculation somebody can check.
V_FRACTION = 0.5


def effective_range(vals):
    """Reach in metres: control range for a guided round, v50 for a bullet."""
    for k in ("maxControlRange", "missileLockMaxDistance"):
        if vals.get(k):
            return round(float(vals[k]))
    drag = vals.get("airFriction")
    if not drag or drag >= 0:
        return None
    return round(math.log(V_FRACTION) / float(drag))


def penetrator(name, vals, ammo):
    """The caliber of the submunition that actually does the penetrating."""
    sub = vals.get("submunitionAmmo")
    if not sub or sub not in ammo:
        return None
    return ammo[sub].get("caliber")


def fmt(v):
    if v is None:
        return ""
    if isinstance(v, str):
        return v
    r = round(v, 5)
    return str(int(r)) if r == int(r) else ("%g" % r)


def main():
    if not os.path.isfile(DATA):
        print("no %s - run tools/gen_vanilla_ammo.py first" % DATA)
        return 1
    ammo = json.load(io.open(DATA, encoding="utf-8"))

    buckets = [(title, re.compile(pat), []) for title, pat in GROUPS]
    for name in sorted(ammo, key=str.lower):
        for _, pat, rows in buckets:
            if pat.search(name):
                rows.append(name)
                break

    out = [
        "# Base game ammunition",
        "",
        "Every `CfgAmmo` class the base game defines that carries a lethality or",
        "ballistic figure, with its **resolved** values - a tracer round shows the",
        "numbers it inherits, not the two lines its own class declares.",
        "",
        "Generated by `tools/gen_ammo_doc.py` from `work/vanilla_ammo.json`, which",
        "`tools/gen_vanilla_ammo.py` builds by reading the unpacked A3 tree. Do not",
        "hand-edit.",
        "",
        "**What the columns mean.**",
        "",
        "| Column | Is |",
        "|---|---|",
        "| `hit` | damage on a direct strike |",
        "| `indHit` / `indRange` | the splash and its radius |",
        "| `blast` | the `explosive` field - the share of damage delivered as pressure rather than kinetic energy. **This is the only overpressure figure the base game has.** ACE's `ace_frag_*` and overpressure fields exist only on modded rounds. |",
        "| `caliber` | the penetration multiplier of the round body |",
        "| `pen` | the penetration of the round's **submunition**, where it has one. A HEAT warhead spawns a penetrator and that is what defeats armour - the parent's own caliber describes the shell. |",
        "| `speed` / `drag` | the ballistics that decide drop and lead |",
        "| `effRange` | **derived, not config.** Guided rounds use their control or lock range. Bullets use the distance to half muzzle velocity: Arma's drag is exponential, so `ln(0.5)/airFriction` is independent of muzzle speed and compares two rounds fairly. Arma has no effective-range field for a bullet, and inventing one would be worse than a calculation you can check. |",
        "| `warhead` | selects the damage model |",
        "",
        "This is the floor the tiered futureAmmo rounds are measured against - see",
        "`tools/gen_fa_tiers.py`.",
        "",
        "| Group | Classes |",
        "|---|---:|",
    ]
    for title, _, rows in buckets:
        if rows:
            out.append("| %s | %d |" % (title, len(rows)))
    out.append("| **Total** | **%d** |" % len(ammo))
    out.append("")

    for title, _, rows in buckets:
        if not rows:
            continue
        out.append("## %s (%d)" % (title, len(rows)))
        out.append("")
        out.append("| Class | " + " | ".join(h for _, h in COLS) + " |")
        out.append("|---|" + "---:|" * (len(COLS) - 1) + "---|")
        for name in rows:
            vals = dict(ammo[name])
            vals["_eff"] = effective_range(vals)
            vals["_pen"] = penetrator(name, vals, ammo)
            cells = [fmt(vals.get(k)) for k, _ in COLS]
            out.append("| `%s` | %s |" % (name, " | ".join(cells)))
        out.append("")

    io.open(OUT, "w", encoding="utf-8", newline="\r\n").write("\n".join(out) + "\n")
    print("%d ammo class(es) -> %s" % (len(ammo), OUT))
    for title, _, rows in buckets:
        if rows:
            print("  %-32s %d" % (title, len(rows)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
