class Source:
    """One config file of a base addon."""

    def __init__(self, addon, path, comp, prefix):
        self.addon, self.path, self.comp = addon, path, comp
        self.text = open(path, encoding="utf-8", errors="replace", newline="").read()
        self.mt = mask(self.text)
        self.bs = blocks(self.text, self.mt)
        for b in self.bs:                     # a file #included inside a class sits in that class's path
            b["path"] = [n for n, _p in prefix] + b["path"]
            b["chain"] = list(prefix) + b["chain"]
            b["depth"] = len(b["path"])


def walk_sources():
    """Every .hpp/.cpp of the base addons, with the class path each sits in when #included."""
    out = []
    for a in sorted(os.listdir(ADDONS)):
        d = os.path.join(ADDONS, a)
        if not os.path.isdir(d) or a in SKIP_DIRS or a in DLC_ONLY:
            continue
        comp = component(d)
        files = [os.path.join(dp, f) for dp, _dn, fs in os.walk(d) for f in fs if f.lower().endswith((".hpp", ".cpp"))]
        prefix = {}

        def prefix_of(p, seen=()):
            key = os.path.normcase(os.path.abspath(p))
            if key in prefix:
                return prefix[key]
            prefix[key] = []
            for q in files:
                if q in seen:
                    continue
                t = open(q, encoding="utf-8", errors="replace").read()
                for m in re.finditer(r'(?m)^[ \t]*#include\s+"([^"]+)"', t):
                    tgt = os.path.normcase(os.path.abspath(os.path.join(os.path.dirname(q), m.group(1).replace("\\", os.sep))))
                    if tgt != key:
                        continue
                    opened = sorted((b for b in blocks(t, mask(t)) if b.get("body") and b["body"][0] < m.start() < b["body"][1]),
                                    key=lambda b: b["kstart"])
                    prefix[key] = prefix_of(q, seen + (p,)) + [(b["name"], b["parent"]) for b in opened]
                    return prefix[key]
            return prefix[key]
        for p in files:
            out.append(Source(a, p, comp, prefix_of(p)))
    return out


def find_dead(sources):
    """resolved class name -> set of DLC tags, for every jmfsb class that needs a DLC, and why."""
    defs = collections.defaultdict(list)
    for s in sources:
        for b in s.bs:
            if not b["extern"] and b["depth"] == 1 and b["path"][0].lower() in TABLES - {"cfggroups"}:
                r = resolve(b["name"], s.comp)
                if r:
                    defs[r].append((s, b))
    dead, why = {}, {}
    changed = True
    while changed:
        changed = False
        for r, lst in defs.items():
            if r in dead:
                continue
            for s, b in lst:
                tags, reason = set(), None
                par = resolve(b["parent"], s.comp) if b["parent"] else None
                body = direct_body(s.text, b, s.bs) if b.get("body") else ""
                if par and par in dead:
                    tags, reason = set(dead[par]), "parent " + par
                elif par and par not in defs and name_tags(par):
                    tags, reason = name_tags(par), "parent " + par
                elif name_tags(r):
                    tags, reason = name_tags(r), "a DLC class"
                elif any(rx.search(body) for rx in DLC_PATH.values()):
                    tags, reason = {t for t, rx in DLC_PATH.items() if rx.search(body)}, "DLC files"
                else:
                    um = re.search(r"\buniformClass\s*=\s*([^;]+);", body)
                    u = resolve(um.group(1), s.comp) if um else None
                    if u and (u in dead or name_tags(u)):
                        tags, reason = set(dead.get(u) or name_tags(u)), "uniform " + u
                if tags:
                    dead[r], why[r] = tags, (s.addon, reason)
                    changed = True
                    break
    return dead, why


# ------------------------------------------------------------------ the overlays
class Node:
    def __init__(self, header):
        self.header = header                  # "class X: Y" (globalized) or None for the root
        self.kids = collections.OrderedDict()
        self.lines = []
        self.raw = []


class Overlay:
    def __init__(self, tags, owner=None):
        self.tags, self.owner = tuple(sorted(tags)), owner
        self.name = "cdlc_" + "_".join(self.tags) + ("_" + owner if owner else "")
        self.root = Node(None)
        self.units, self.weapons = [], []
        self.jmfsb = set()                    # jmfsb CfgPatches it patches or names
        self.macros = collections.OrderedDict()   # the source addons' own #defines its text uses

    def node(self, chain, comp):
        n = self.root
        for name, parent in chain:
            g = globalize(name, comp)
            key = g.lower()
            if key not in n.kids:
                n.kids[key] = Node("class %s%s" % (g, ": " + globalize(parent, comp) if parent else ""))
            n = n.kids[key]
        return n

    def render(self, index):
        lines = []
        decl = declarations(self, index)
        for tkey, table in self.root.kids.items():
            skel, glob = decl.get(tkey, ({}, set()))
            nodes = collections.OrderedDict()
            for key, n in skel.items():                       # skeletons, each merged with this overlay's update of it
                nodes[key] = n
            for key, n in table.kids.items():
                if key in nodes:
                    merge(nodes[key], n)
                    nodes[key].lines = n.lines + [x for x in nodes[key].lines if x not in n.lines]
                else:
                    nodes[key] = n
            order = parents_first_nodes(nodes)
            defined = set(nodes) | {head(r)[0] for r in table.raw}
            parents = {parse_header(n.header)[1] for n in nodes.values()} | {CLASS_RE.search(mask(r)).group(2) for r in table.raw
                                                                           if CLASS_RE.search(mask(r))}
            ext = sorted({x for x in parents | glob if x and x.lower() not in defined}, key=str.lower)
            lines.append("%s {" % table.header)
            lines += ["    class %s;" % x for x in ext]
            if ext:
                lines.append("")
            lines += ["    " + x for x in table.lines]
            for n in order:
                lines += self._node(n, 1)
            for raw in parents_first(table.raw):
                lines.append(raw.rstrip("\r\n").replace("\r\n", "\n"))
            lines.append("};")
            lines.append("")
        return "\n".join(lines)

    def _node(self, n, depth):
        ind = "    " * depth
        if n.header.endswith(";"):
            return [ind + n.header]
        out = ["%s%s {" % (ind, n.header)]
        out += self._body(n, depth + 1)
        out.append("%s};" % ind)
        return out

    def _body(self, n, depth):
        ind = "    " * depth
        out = [ind + x for x in n.lines]
        for raw in parents_first(n.raw):
            out.append(raw.rstrip("\r\n").replace("\r\n", "\n"))
        for k in n.kids.values():
            out += self._node(k, depth)
        return out


CORE = re.compile(r"(?i)^(?:a3_(?!aegis|atlas)|cba_|ace_|acex_|diwako_dui_|acre_)")
_OPTIONAL = {}


def requirements(addon):
    p = os.path.join(ADDONS, addon, "config.cpp")
    if not os.path.exists(p):
        return []
    m = re.search(r"requiredAddons\[\]\s*=\s*\{([^}]*)\}", strip_com(open(p, encoding="utf-8", errors="replace").read()))
    return re.findall(r'"([^"]+)"', m.group(1)) if m else []


def optional_mods(addon, seen=()):
    """What a base addon needs beyond the base game, CBA, ACE and jmfsb's always-loaded addons - other mods, directly
    or through the jmfsb addons it requires. Such an addon's DLC content gets an overlay of its own, so a missing mod
    does not take every other faction's DLC content with it."""
    if addon in _OPTIONAL:
        return _OPTIONAL[addon]
    out = []
    for r in requirements(addon):
        if r.lower().startswith("jmfsb_"):
            dep = next((a for a in os.listdir(ADDONS) if "jmfsb_" + component(os.path.join(ADDONS, a)) == r), None)
            if dep and dep not in seen and dep != addon and dep not in DLC_ONLY and optional_mods(dep, seen + (addon,)):
                out.append(r)
        elif not CORE.match(r) and not DLC_REQ.match('"%s"' % r):
            out.append(r)
    _OPTIONAL[addon] = out
    return out


def head(raw):
    m = CLASS_RE.search(mask(raw))
    return (m.group(1).lower(), (m.group(2) or "").lower()) if m else ("", "")


def parents_first_nodes(nodes):
    """Top-level nodes of a table, a node's parent (when also a node here) before it."""
    out, done, todo = [], set(), list(nodes.items())
    while todo:
        rest = [(k, n) for k, n in todo if (parse_header(n.header)[1] or "").lower() in nodes
                and (parse_header(n.header)[1] or "").lower() not in done and (parse_header(n.header)[1] or "").lower() != k]
        for k, n in todo:
            if (k, n) not in rest:
                out.append(n)
                done.add(k)
        if len(rest) == len(todo):
            out += [n for _k, n in rest]
            break
        todo = rest
    return out


def parents_first(raws):
    """Moved classes in an order where a class's parent, when moved too, comes before it."""
    names = {head(r)[0] for r in raws}
    out, done, todo = [], set(), list(raws)
    while todo:
        rest = []
        for r in todo:
            name, par = head(r)
            if par in names and par not in done and par != name:
                rest.append(r)
            else:
                out.append(r)
                done.add(name)
        if len(rest) == len(todo):             # a cycle: keep source order
            out += rest
            break
        todo = rest
    return out


def plan(sources, dead):
    """-> ({tags: Overlay}, {path: new text}, report lines)"""
    overlays, edits, notes = {}, {}, []
    owner_of = {}

    def ov(tags):
        tags = tuple(sorted(tags))
        key = (tags, owner_of[cur[0]], cur[0])          # a fragment: one source addon's part of one overlay
        if key not in overlays:
            overlays[key] = Overlay(tags, key[1])
            overlays[key].jmfsb.add(cur[0])
        return overlays[key]
    cur = [None]

    def item_tags(r):
        return set(dead.get(r) or name_tags(r or ""))

    for s in sources:
        t, mt, comp = s.text, s.mt, s.comp
        spans = []
        cur[0] = s.addon
        nested_tags = {}                      # (path, name) of a nested class moved here -> its DLCs
        if s.addon not in owner_of:
            owner_of[s.addon] = s.addon if optional_mods(s.addon) else None

        def covered(i, j):
            return any(a <= i and j <= z for a, z, rep in spans if rep == "")

        # 1. whole classes and nested ones on DLC files; group slots naming a moved unit
        for b in sorted(s.bs, key=lambda x: x["depth"]):
            if not b["path"] or covered(b["start"], b["end"]):
                continue
            top = b["path"][0].lower()
            r = resolve(b["name"], comp)
            if top == "cfgpatches":
                continue
            if b["extern"]:
                if r in dead or name_tags(r):
                    spans.append((b["start"], b["end"], ""))
                continue
            if b.get("body") is None:
                continue
            tags = None
            if b["depth"] == 1 and top in TABLES and r in dead:
                tags = dead[r]
            elif any(x.lower() in XTD for x in b["path"]) and b["depth"] >= 2 and (r in dead or name_tags(r)):
                tags = item_tags(r)
            elif b["depth"] >= 2 and top in TABLES and top != "cfggroups":
                body = direct_body(t, b, s.bs)
                hit = {g for g, rx in DLC_PATH.items() if rx.search(body)}
                # a cargo entry or a linked attachment naming a DLC class (weapon = "arifle_Galat_lxWS")
                for m in re.finditer(r"\b(?:weapon|magazine|item|backpack|name)\s*=\s*([^;{}\n]+);", body):
                    hit |= item_tags(resolve(m.group(1), comp))
                if hit:
                    tags = hit
            elif top == "cfggroups":
                vm = re.search(r"\bvehicle\s*=\s*([^;]+);", direct_body(t, b, s.bs))
                v = resolve(vm.group(1), comp) if vm else None
                if v and item_tags(v):
                    tags = item_tags(v)
            if tags:
                o = ov(tags)
                o.node(b["chain"], comp).raw.append(globalize(t[b["start"]:b["end"]], comp))
                o.jmfsb.add(s.addon)
                if b["depth"] >= 2:
                    nested_tags[(tuple(b["path"]), b["name"].lower())] = set(tags)
                spans.append((b["start"], b["end"], ""))
                if b["depth"] == 1 and top == "cfgvehicles" and re.search(r"\bscope\s*=\s*2", t[b["start"]:b["end"]]):
                    o.units.append(globalize(re.sub(r"^GVAR", "QGVAR", b["name"]) if b["name"].startswith("GVAR") else '"%s"' % b["name"], comp))
                elif b["depth"] == 1 and top == "cfgweapons" and re.search(r"\bscope\s*=\s*[12]", t[b["start"]:b["end"]]):
                    o.weapons.append(globalize(re.sub(r"^GVAR", "QGVAR", b["name"]) if b["name"].startswith("GVAR") else '"%s"' % b["name"], comp))
        # a nested class whose sibling parent moved goes with it (Missiles_reloadMagazine: Missiles_revolving)
        moved_nested = dict(nested_tags)
        changed = True
        while changed:
            changed = False
            for b in s.bs:
                if b["depth"] < 2 or b["extern"] or not b["parent"] or covered(b["start"], b["end"]):
                    continue
                key = (tuple(b["path"]), b["parent"].lower())
                if key in moved_nested:
                    tags = moved_nested[key]
                    o = ov(tags)
                    o.node(b["chain"], comp).raw.append(globalize(t[b["start"]:b["end"]], comp))
                    spans.append((b["start"], b["end"], ""))
                    moved_nested[(tuple(b["path"]), b["name"].lower())] = tags
                    changed = True
        # groups and categories every slot of which moved go whole (their slots already copied above)
        changed = True
        while changed:
            changed = False
            for b in s.bs:
                if b["extern"] or b.get("body") is None or covered(b["start"], b["end"]) or not b["path"]:
                    continue
                if b["path"][0].lower() != "cfggroups" or b["depth"] < 2:
                    continue
                kids = [c for c in s.bs if not c["extern"] and c["path"] == b["path"] + [b["name"]] and b["kstart"] < c["kstart"] and c["end"] <= b["end"]]
                if kids and all(covered(c["start"], c["end"]) for c in kids):
                    spans.append((b["start"], b["end"], ""))
                    changed = True

        def enclosing(pos):
            c = [b for b in s.bs if b.get("body") and b["body"][0] < pos < b["body"][1]]
            return max(c, key=lambda b: b["depth"]) if c else None

        def chain_at(pos):
            b = enclosing(pos)
            return b["chain"] + [(b["name"], b["parent"])] if b else None

        # 2. arrays: DLC items out (or swapped for their stand-ins), appended back in the overlay
        swapped_classes = {}
        for m in re.finditer(r"\b(\w+)\[\]\s*(\+?=)\s*\{", mt):
            i, d = m.end(), 1
            while d and i < len(mt):
                d += {"{": 1, "}": -1}.get(mt[i], 0)
                i += 1
            ia, iz = m.end(), i - 1
            if covered(m.start(), i):
                continue
            key, raw = m.group(1), t[ia:iz]
            chain = chain_at(m.start())
            if chain is None:
                continue
            top = chain[0][0].lower()
            if "{" in mt[ia:iz]:                         # nested (ALiVE loadouts): stand-in strings only
                new = raw
                for a, z in STANDIN_TEXT:
                    new = new.replace(a, z)
                if new != raw:
                    spans.append((ia, iz, new))
                    o = ov({"rf"})
                    o.node(chain, comp).lines.append("%s[] = {%s};" % (key, globalize(raw, comp)))
                    o.jmfsb.add(s.addon)
                continue
            elems = split_masked(raw, mt[ia:iz])
            toks = [strip_com(raw[a:z]) for a, z in elems]
            res = [resolve(x, comp) for x in toks]
            gone = [k for k, r in enumerate(res) if r and item_tags(r)]
            if not gone:
                continue
            if top == "cfgpatches":                      # units[] / weapons[]: the overlay lists its own
                spans.append((ia, iz, ", ".join(toks[k] for k in range(len(toks)) if k not in gone).join(["\n            ", "\n        "]) if len(gone) < len(toks) else ""))
                continue
            stand = {}
            for k in gone:
                for rx, rep, mags in STANDINS:
                    if rx.search(res[k]):
                        stand[k] = rep
                        if mags:
                            swapped_classes[tuple(chain)] = (mags, item_tags(res[k]))
            keep = [toks[k] if k not in gone else stand[k] for k in range(len(toks)) if k not in gone or k in stand]
            spans.append((ia, iz, ", ".join(keep)))
            for tags, ks in _by_tags([(item_tags(res[k]), k) for k in gone]).items():
                o = ov(tags)
                n = o.node(chain, comp)
                if stand:
                    n.lines.append("%s[] = {%s};" % (key, ", ".join(globalize(x, comp) for x in toks)))
                else:
                    n.lines.append("%s[] += {%s};" % (key, ", ".join(globalize(toks[k], comp) for k in ks)))
                o.jmfsb.add(s.addon)
        # the stand-in weapon's magazines, in the same class
        for m in re.finditer(r"\b((?:respawnM|m)agazines)\[\]\s*=\s*\{", mt):
            chain = chain_at(m.start())
            if not chain or tuple(chain) not in swapped_classes:
                continue
            i, d = m.end(), 1
            while d:
                d += {"{": 1, "}": -1}.get(mt[i], 0)
                i += 1
            ia, iz = m.end(), i - 1
            if any(a <= ia and iz <= z for a, z, _r in spans):
                continue
            toks = [strip_com(t[ia:iz][a:z]) for a, z in split_masked(t[ia:iz], mt[ia:iz])]
            swap, swap_tags = swapped_classes[tuple(chain)]
            if not any((resolve(x, comp) or "") in swap for x in toks):
                continue
            new, done = [], set()
            for x in toks:
                r = resolve(x, comp) or ""
                if r in swap:
                    if r not in done:
                        new += swap[r]
                        done.add(r)
                else:
                    new.append(x)
            spans.append((ia, iz, ",".join(new)))
            o = ov(swap_tags)
            o.node(chain, comp).lines.append("%s[] = {%s};" % (m.group(1), ", ".join(globalize(x, comp) for x in toks)))
        # 3. a crew / backpack naming a moved class: the parent's stays in the base
        for m in re.finditer(r"(?m)^[ \t]*(crew|backpack)\s*=\s*([^;{}\n]+);[ \t]*\r?\n?", mt):
            if covered(m.start(), m.end()):
                continue
            val = t[m.start(2):m.end(2)]
            r = resolve(val, comp)
            if r and item_tags(r):
                chain = chain_at(m.start())
                o = ov(item_tags(r))
                o.node(chain, comp).lines.append("%s = %s;" % (m.group(1), globalize(val.strip(), comp)))
                o.jmfsb.add(s.addon)
                spans.append((m.start(), m.end(), ""))
        if spans:
            edits[s.path] = apply_spans(t, spans, notes, s.path)
    return overlays, edits, notes


def _by_tags(pairs):
    out = collections.OrderedDict()
    for tags, k in pairs:
        out.setdefault(tuple(sorted(tags)), []).append(k)
    return out


def apply_spans(t, spans, notes, path):
    spans.sort(key=lambda s: (s[0], -s[1]))
    merged = []
    for s in spans:
        if merged and s[0] < merged[-1][1]:
            if merged[-1][2] == "" and s[1] <= merged[-1][1]:
                continue
            notes.append("%s: overlapping edits at %d" % (os.path.relpath(path, ROOT), s[0]))
            continue
        merged.append(s)
    out, last = [], 0
    for a, z, rep in merged:
        out += [t[last:a], rep]
        last = z
    return "".join(out + [t[last:]])


