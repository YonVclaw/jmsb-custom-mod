def prune_unused():
    """Declarations nothing uses any more - in a base file the classes that used them left, in an overlay a skeleton
    asked for more than HEMTT needed: HEMTT lists them (L-C14, .hemttout/unused_external_classes.txt); they go,
    until it lists none."""
    import subprocess
    listing = os.path.join(ROOT, ".hemttout", "unused_external_classes.txt")
    for _ in range(5):
        if os.path.exists(listing):
            os.remove(listing)
        subprocess.run(["hemtt", "check"], cwd=ROOT, capture_output=True)
        if not os.path.exists(listing):
            return
        by_file = collections.defaultdict(list)
        for line in open(listing, encoding="utf-8", errors="replace"):
            m = re.match(r"(\w+) - (\S+):(\d+):\d+", line.strip())
            if m:
                by_file[m.group(2)].append((int(m.group(3)), m.group(1)))
        cut = 0
        for rel, hits in by_file.items():
            p = os.path.join(ROOT, rel)
            text = open(p, encoding="utf-8", newline="").read()
            lines = text.split("\n")
            for n, name in sorted(hits, reverse=True):
                if lines[n - 1].strip().rstrip("\r") == "class %s;" % name:
                    del lines[n - 1]
                    cut += 1
            open(p, "w", encoding="utf-8", newline="").write("\n".join(lines))
        print("pruned %d unused declarations" % cut)
        if not cut:
            return


