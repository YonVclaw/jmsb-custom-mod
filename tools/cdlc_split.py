# ------------------------------------------------------------------ naming
def component(addon_dir):
    p = os.path.join(addon_dir, "script_component.hpp")
    if os.path.exists(p):
        m = re.search(r"#define COMPONENT (\w+)", open(p, encoding="utf-8", errors="replace").read())
        if m:
            return m.group(1)
    return os.path.basename(addon_dir)


def resolve(tok, comp):
    """A config token -> the class name it means (lowercase), or None."""
    t = tok.strip()
    for pat, fmt in ((r'"([^"]*)"', "%s"), (r"Q?GVAR\((\w+)\)", "jmfsb_%s_%%s" % comp), (r"QUOTE\((\w+)\)", "%s")):
        m = re.fullmatch(pat, t)
        if m:
            return (fmt % m.group(1)).lower()
    m = re.fullmatch(r"Q?EGVAR\((\w+),\s*(\w+)\)", t)
    if m:
        return ("jmfsb_%s_%s" % (m.group(1), m.group(2))).lower()
    return t.lower() if re.fullmatch(r"\w+", t) else None


DLC_DIR = {"ws": "lxws", "rf": "rf", "ef": "ef", "gm": "gm"}


def name_tags(n):
    """The DLCs a class name says it belongs to (jmfsb's own classes are judged by what they build on). A file path
    is a DLC's only when it points into the DLC - jmfsb's own sheets carry names like ..._ION_lxWS_CO.paa."""
    if not n or NOT_DLC.search(n) or n.startswith("jmfsb_"):
        return set()
    if any(ch in n for ch in "\\/."):
        return {tag for tag, d in DLC_DIR.items() if re.match(r"(?i)\\?%s\\" % d, n)}
    return {tag for tag, (rx, _p, _n) in DLC.items() if rx.search(n)}


def globalize(text, comp):
    """Text moved out of addon `comp` into an overlay: its own-addon macros spelled out against `comp`."""
    text = re.sub(r"\bQGVAR\(", "QEGVAR(%s," % comp, text)
    text = re.sub(r"(?<![EQ])\bGVAR\(", "EGVAR(%s," % comp, text)
    text = re.sub(r"\bQPATHTOF\(", "QPATHTOEF(%s," % comp, text)
    text = re.sub(r"(?<!Q)\bPATHTOF\(", "PATHTOEF(%s," % comp, text)
    text = re.sub(r"\bQFUNC\(", "QEFUNC(%s," % comp, text)
    text = re.sub(r"(?<![EQ])\bFUNC\(", "EFUNC(%s," % comp, text)
    text = re.sub(r"\bQUOTE\(ADDON\)", '"jmfsb_%s"' % comp, text)
    return re.sub(r"\bADDON\b", "DOUBLES(PREFIX,%s)" % comp, text)


# ------------------------------------------------------------------ lexing
def mask(text):
    """Strings, comments and preprocessor lines blanked (same length): braces and words in them vanish."""
    out, i, n = list(text), 0, len(text)
    while i < n:
        c = text[i]
        if c == '"':
            j = i + 1
            while j < n and not (text[j] == '"' and not text.startswith('""', j)):
                j += 2 if text.startswith('""', j) else 1
            for k in range(i + 1, min(j, n)):
                if out[k] != "\n":
                    out[k] = "_"
            i = j + 1
        elif text.startswith("//", i) or text.startswith("/*", i) or (c == "#" and text[:i].rstrip(" \t").endswith(("\n", "")) and
                                                                         (i == 0 or text[text.rfind("\n", 0, i) + 1:i].strip() == "")):
            if text.startswith("/*", i):
                j = text.find("*/", i + 2)
                j = n if j < 0 else j + 2
            else:
                j = i
                while True:
                    k = text.find("\n", j)
                    if k < 0:
                        k = n
                        break
                    if c == "#" and text[k - 1:k] == "\\" or c == "#" and text[k - 2:k] == "\\\r":
                        j = k + 1
                        continue
                    break
                j = k
            for k in range(i, j):
                if out[k] != "\n":
                    out[k] = " "
            i = j
        else:
            i += 1
    return "".join(out)


CLASS_RE = re.compile(r"\bclass\s+(\w+(?:\([\w, ]+\))?)\s*(?::\s*(\w+(?:\([\w, ]+\))?))?\s*(\{|;)")


def blocks(text, mt):
    """Every class: name, parent, start (line start), kstart, end (past `};` and its newline), body, path, depth."""
    out, stack, pending = [], [], {}
    events = [("class", m.start(), m) for m in CLASS_RE.finditer(mt)]
    events += [(ch, i, None) for i, ch in enumerate(mt) if ch in "{}"]
    events.sort(key=lambda e: (e[1], 0 if e[0] == "class" else 1))
    for kind, i, m in events:
        if kind == "class":
            b = {"name": m.group(1), "parent": m.group(2), "start": text.rfind("\n", 0, m.start()) + 1, "kstart": m.start(),
                 "path": [d["name"] for d in stack if d is not None], "chain": [(d["name"], d["parent"]) for d in stack if d is not None],
                 "extern": m.group(3) == ";"}
            b["depth"] = len(b["path"])
            if b["extern"]:
                e = m.end()
                nl = text.find("\n", e)
                b["end"] = nl + 1 if nl >= 0 and text[e:nl].strip() == "" else e
                out.append(b)
            else:
                pending[m.end() - 1] = b
        elif kind == "{":
            stack.append(pending.pop(i, None))
        elif stack:
            b = stack.pop()
            if b is None:
                continue
            j = i + 1
            while j < len(mt) and mt[j] in " \t":
                j += 1
            j += mt[j:j + 1] == ";"
            nl = text.find("\n", j)
            b["end"] = nl + 1 if nl >= 0 and text[j:nl].strip() == "" else j
            b["body"] = (text.find("{", b["kstart"]), i)
            out.append(b)
    return out


def direct_body(text, b, bs):
    """The class's own properties: nested class bodies blanked."""
    a, z = b["body"]
    s = list(text[a:z])
    for c in bs:
        if c is not b and c.get("body") and a < c["kstart"] and c["end"] <= z + 2:
            for k in range(c["kstart"] - a, min(c["end"], z) - a):
                if s[k] != "\n":
                    s[k] = " "
    return "".join(s)


def split_masked(raw, masked):
    """Top-level comma split of an array interior: [(start, end)] of each element's text, trimmed."""
    out, depth, last = [], 0, 0
    for i, ch in enumerate(masked + ","):
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        elif ch == "," and depth == 0:
            seg = masked[last:i]
            a = last + len(seg) - len(seg.lstrip())
            z = last + len(seg.rstrip())
            if z > a:
                out.append((a, z))
            last = i + 1
    return out


def strip_com(x):
    return re.sub(r"/\*.*?\*/", "", re.sub(r"//[^\n]*", "", x), flags=re.S).strip()


