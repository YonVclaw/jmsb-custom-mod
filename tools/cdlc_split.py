DLC_REQ = re.compile(r'\s*"(?:data_f_lxWS_Loadorder|RF_Data_Loadorder|RF_Weapons|EF_\w+|gm_\w+|jmfsb_fa_rf|jmfsb_fa_ef|'
                     r'jmfsb_fa_antidrone_ef|jmfsb_optics_ef|jmfsb_vests_efa)"\s*,?')


def strip_requirements(text):
    """A base addon's config.cpp without the DLCs (and the DLC-only jmfsb addons) in its requiredAddons."""
    m = re.search(r"requiredAddons\[\]\s*=\s*\{([^}]*)\}", text)
    if not m:
        return text
    inner = DLC_REQ.sub("", m.group(1))
    inner = re.sub(r",(\s*)$", r"\1", inner)
    inner = re.sub(r",\s*(//[^\n]*\n\s*)$", r"\1", inner)
    return text[:m.start(1)] + inner + text[m.end(1):]


def defined_names(o):
    out = set()
    for n in _walk(o.root):
        out |= {head(r)[0] for r in n.raw}
    return out


