def tmt_camo(cls, disp):
    s = (cls + " " + (disp or "")).lower()
    if re.search(r"_w\b|_w_|woodland|\(w\)|_w$", s):
        return "W"
    if re.search(r"_e\b|_e_|east|_d\b|\(d\)|_d$", s):
        return "E"
    return None


def uniform_arid(u):
    if not u:
        return None
    for a, b in (("tmt_kkk_green_", "tmt_desert_tan_"), ("tmt_kkk_", "tmt_desert_"), ("tmt_digital_green_", "tmt_desert_tan_"),
                 ("tmt_digital_", "tmt_desert_")):
        if u.startswith(a):
            return u.replace(a, b, 1)
    return None


