def ru_full(tok):
    """A kit token as the game names the class: QEGVAR(weapons,X) -> jmfsb_weapons_X, uniform_ru's own with its prefix."""
    m = re.match(r"Q?EGVAR\((\w+),\s*(\w+)\)", tok)
    if m:
        return "jmfsb_%s_%s" % (m.group(1), m.group(2))
    m = re.match(r"Q?GVAR\((\w+)\)", tok)
    if m:
        return "jmfsb_uniform_ru_" + m.group(1)
    return ru_name(tok)


