def vkind(u):
    """What a vehicle is for the groups."""
    cls, sub = u["class"].lower(), (u.get("editorsubcategory") or "")
    sim = (u.get("simulation") or "").lower()
    disp = str(u.get("displayname") or "").lower()
    crew = str(u.get("crew") or "")
    if "uav_ai" in crew.lower() or "uav" in cls or "tb2" in cls or "drone" in sub.lower():
        return "uav"
    if sub == "EdSubcat_Turrets" or "static" in cls or "torna" in cls:
        return "static"
    if sim.startswith("ship") or sub == "EdSubcat_Boats":
        return "boat"
    if sim.startswith("airplane") or sub == "EdSubcat_Planes" and "helicopter" not in sim:
        if int(float(u.get("transportsoldier") or 0)) > 8 or re.search(r"c130|y20|y9|transport", cls):
            return "plane_transport"
        return "plane"
    if sim.startswith("helicopter") or sub == "EdSubcat_Helicopters":
        ts = int(float(u.get("transportsoldier") or 0))
        if re.search(r"ah1|ka_52|z10|z19|attack", cls):
            return "heli_attack"
        if re.search(r"unarmed|heli_light|transport|ch47|s70|t70|z8|z20|z11", cls):
            return "heli_transport"
        return "heli_attack" if ts <= 2 else "heli_transport"
    if sub == "EdSubcat_AAs" or re.search(r"_aa\b|pgz|sa_22|hq6|zipkin", cls):
        return "aa"
    if sub == "EdSubcat_Artillery" or re.search(r"t155|2b26|plz|pll|grad", cls):
        return "arty"
    if re.search(r"amb|medic|medical", cls + disp):
        return "support_med"
    if re.search(r"ammo|fuel|repair|_box|flat", cls):
        return "support"
    if sub == "EdSubcat_Tanks" or re.search(r"leo|m60|t_14|ztz|ztq|ztd|mbt", cls):
        return "tank"
    if sim.startswith("tank") or sub == "EdSubcat_APCs" or re.search(r"zbd|zbl|ztl|acv|m113|t_15|arma_", cls):
        return "apc"
    if re.search(r"truck|unimog|kamaz|sx2|transport_?$|transport_w", cls):
        return "truck"
    if re.search(r"hmg|rcws|gmg|armed|_m2|_at\b|_gl_f", cls):
        return "car_armed"
    return "car"


# ------------------------------------------------------------------ old-faction text
def class_blocks(text):
    """Top-level classes inside the first `class CfgVehicles {` (or the given table): name -> (parent, text)."""
    out = collections.OrderedDict()
    for m in re.finditer(r"(?m)^    class (\S+?)\s*:\s*(\S+)\s*\{", text):
        i, d = m.end(), 1
        while d:
            d += {"{": 1, "}": -1}.get(text[i], 0)
            i += 1
        j = text.find("\n", i)
        out[m.group(1)] = (m.group(2), text[m.start():j + 1 if j >= 0 else i])
    return out


def externs(text):
    m = re.search(r"class CfgVehicles \{\n(.*?)\n\n", text, re.S)
    return re.findall(r"(?m)^    class (\S+);", m.group(1)) if m else []


def group_blocks(text, category):
    """The text of one CfgGroups category (`class Infantry {...}`) at the faction level."""
    m = re.search(r"(?m)^            class %s \{" % category, text)
    if not m:
        return None
    i, d = m.end(), 1
    while d:
        d += {"{": 1, "}": -1}.get(text[i], 0)
        i += 1
    return text[m.start():i] + ";"


