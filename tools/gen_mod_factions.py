    def preset_text(self):
        """CfgWeapons lines for the suppressed presets, in gen_us_factions.py's shape."""
        if not self.presets:
            return [], []
        W = self.weapons_db
        decl, body = [], []
        for w in sorted(self.presets, key=str.lower):
            info = W[w]
            if info.get("linked"):
                decl += ["    class %s: %s {" % (w, info.get("parent")), "        class LinkedItems;", "    };"]
            else:
                decl.append("    class %s;" % w)
            body += ["    class GVAR(%s_snds): %s {" % (w, w), "        scope = 1;", "        author = QAUTHOR;",
                     '        baseWeapon = "%s";' % (info.get("baseweapon") or w),
                     "        class LinkedItems%s {" % (": LinkedItems" if info.get("linked") else ""),
                     "            class LinkedItemsMuzzle {", '                slot = "MuzzleSlot";',
                     '                item = "%s";' % self.presets[w], "            };", "        };", "    };"]
        parents = sorted({W[w].get("parent") for w in self.presets if W[w].get("linked")} - set(self.presets))
        return ["    class %s;" % p for p in parents] + decl, body

    def write(self, intro):
        decl, body = self.preset_text()
        vdecl, vbody, wdecl, wbody = self.wearer_text()
        if wbody:
            hdr = ["// UNIFORM TWINS (tools/gen_mod_factions.py): the mod's uniform on a wearer whose modelSides take",
                   "// this faction's side - the mod's own wearer allows only its side, and the game refuses it."]
            if self.weapons_text is None:
                self.weapons_text = "\n".join([HDR] + hdr + ["class CfgWeapons {"] + wdecl + [""] + wbody + ["};", ""])
            else:
                k = self.weapons_text.rstrip().rfind("};")
                self.weapons_text = self.weapons_text[:k] + "\n".join([""] + hdr + wdecl + [""] + wbody) + "\n};\n"
        if body:
            hdr = ["// SUPPRESSED PRESETS (tools/gen_mod_factions.py): the weapon the mod issues with a base-game",
                   "// suppressor its MuzzleSlot takes linked on; scope 1 and baseWeapon keep the arsenal showing",
                   "// the plain weapon. The man's weapons[] names the preset."]
            if self.weapons_text is None:
                self.weapons_text = "\n".join([HDR] + hdr + ["class CfgWeapons {"] + decl + [""] + body + ["};", ""])
            else:
                k = self.weapons_text.rstrip().rfind("};")
                self.weapons_text = self.weapons_text[:k] + "\n".join([""] + hdr + decl + [""] + body) + "\n};\n"
        d = os.path.join(ADDONS, self.addon)
        for rel in sorted(self.data_files):
            dst = os.path.join(d, rel)
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            shutil.copyfile(os.path.join(self.data_from, rel), dst)
        V = [HDR, "//", "// EVERY CLASS BUILDS ON A LOADED MOD'S OWN (or a kept jmfsb class). The mods are required in",
             "// config.cpp, so without them the faction is skipped rather than loading empty classes.", "",
             "class CfgVehicles {"]
        V += ["    class %s;" % x for x in sorted(self.decl, key=str.lower)] + self.extra_decl
        V += [x for x in vdecl if x[len("    class "):-1] not in self.decl] + [""]
        V += [b + "\n" for b in vbody + self.blocks]
        V += ["};", ""]
        open(os.path.join(d, "CfgVehicles.hpp"), "w", encoding="utf-8", newline="\n").write("\n".join(V))
        open(os.path.join(d, "CfgGroups.hpp"), "w", encoding="utf-8", newline="\n").write(self.write_groups())
        open(os.path.join(d, "CfgFactionClasses.hpp"), "w", encoding="utf-8", newline="\n").write("\n".join([
            HDR, "class CfgFactionClasses {", "    class ADDON {", '        displayName = "%s";' % self.display,
            "        side = %d;" % self.side, "        priority = %d;" % self.priority,
            '        icon = %s;' % self.icon, '        flag = %s;' % self.flag, "    };", "};", ""]))
        wpath = os.path.join(d, "CfgWeapons.hpp")
        if self.weapons_text is not None:
            open(wpath, "w", encoding="utf-8", newline="\n").write(self.weapons_text)
        elif os.path.exists(wpath):
            os.remove(wpath)
        req = ['"jmfsb_main"'] + ['"jmfsb_%s"' % a for a in sorted(self.requires_jmfsb)] + ['"%s"' % p for p in sorted(self.patches)]
        cfg = ['#include "script_component.hpp"', "", HDR, "class CfgPatches {", "    class ADDON {",
               "        name = COMPONENT_NAME;", "        units[] = {", ",\n".join("            QGVAR(%s)" % u for u in self.units),
               "        };", "        weapons[] = {};", "        requiredVersion = REQUIRED_VERSION;",
               "        // The mods these classes build on - skipped whole without them (see the header of",
               "        // tools/gen_mod_factions.py). Tier magazines are named as strings, so FA is not required.",
               "        requiredAddons[] = {%s};" % ", ".join(req), "        skipWhenMissingDependencies = 1;",
               "        author = QAUTHOR;", "        VERSION_CONFIG;", "    };", "};", "",
               '#include "CfgFactionClasses.hpp"']
        if self.weapons_text is not None:
            cfg.append('#include "CfgWeapons.hpp"')
        cfg += ['#include "CfgVehicles.hpp"', '#include "CfgGroups.hpp"', ""]
        open(os.path.join(d, "config.cpp"), "w", encoding="utf-8", newline="\n").write("\n".join(cfg))
        readme = os.path.join(d, "README.md")
        old = open(readme, encoding="utf-8").read() if os.path.exists(readme) else ""
        k = old.find("<!-- generated below")
        open(readme, "w", encoding="utf-8", newline="\n").write(
            "# %s\n\n`%s`\n\n%s\n\n%s" % (self.display, "jmfsb_" + self.addon, intro, old[k:] if k >= 0 else ""))
        return len(self.units)


