#!/usr/bin/env python3
"""Give every US Army faction a MAAWS gunner.

    python tools/gen_us_maaws.py

Writes maaws.hpp into each US Army faction addon: one new man per faction,
carrying launch_MRAWS_green_F with a high-explosive round and an anti-air one.

WHY A NEW CLASS AND NOT AN EDIT. None of these factions ships a MAAWS gunner -
their heavy AT man carries a Titan, which is a different weapon for a different
job. Editing the Titan gunner would take the Titan out of the army; adding a
class puts the 84 mm alongside it and lets a group template ask for either.

BUILT ON THE RIFLEMAN, NOT ON THE AT SPECIALIST. The AT specialist already
carries a launcher, so building on him gives a man with two - and no way for the
AI to decide which to use. The rifleman is the honest base: a rifle, and the 84
mm slung over it.

APPEND, NEVER ASSIGN. `weapons[] +=` is this project's convention (handoff
section 12) and here it is load-bearing: the rifleman's own rifle, magazines and
kit are whatever his faction gave him, and this file has no business knowing
what they are. Assigning weapons[] outright would silently disarm him of the
rifle it did not name.

ONE HE AND ONE AA ROUND, from futureAmmo:
    FA_MRAWS_HE448_AB    prefragmented HE, programmable airburst
    FA_MRAWS_AAM517_SR   VSHORAD IR missile - helos, low and slow, large UAS
"""
import io
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "work", "factions.json")
ADDONS = os.path.join(ROOT, "addons")

ARMY = [
    ("BLU_F", "faction_blu_f"),
    ("BLU_T_F", "faction_blu_t_f"),
    ("BLU_W_F", "faction_blu_w_f"),
    ("BLU_NATO_lxWS", "faction_blu_nato_lxws"),
]

LAUNCHER = "launch_MRAWS_green_F"
ROUND_HE = "FA_MRAWS_HE448_AB"
ROUND_AA = "FA_MRAWS_AAM517_SR"

# In preference order - the first one a faction actually fields is the base.
BASE_ROLES = ["Rifleman", "Grenadier", "Autorifleman"]


def crlf(path, lines):
    io.open(path, "w", encoding="utf-8", newline="\r\n").write("\n".join(lines) + "\n")


def main():
    if not os.path.isfile(DATA):
        print("no %s" % DATA)
        return 1
    facs = json.load(io.open(DATA, encoding="utf-8"))

    for cls, comp in ARMY:
        d = os.path.join(ADDONS, comp)
        if not os.path.isdir(d):
            print("  %-24s MISSING addon - skipped" % comp)
            continue
        if cls not in facs:
            print("  %-24s not in the dump - skipped" % comp)
            continue

        base = None
        role = None
        for want in BASE_ROLES:
            hit = [u for u in facs[cls]["units"]
                   if u["name"] == want and u["vclass"] == "Men"]
            if hit:
                base = sorted(hit, key=lambda u: len(u["cls"]))[0]["cls"]
                role = want
                break
        if base is None:
            print("  %-24s no rifleman to build on - skipped" % comp)
            continue

        new = "jmfsb_%s_MAAWS_Gunner" % comp.replace("faction_", "")

        crlf(os.path.join(d, "maaws.hpp"), [
            "// THE MAAWS GUNNER.",
            "//",
            "// None of these factions shipped one - their heavy AT man carries a Titan,",
            "// which is a different weapon for a different job. So this is a new man",
            "// rather than an edit: the Titan stays in the army and a group template can",
            "// ask for either.",
            "//",
            "// BUILT ON THE %s (%s), not on the AT specialist. The AT" % (role.upper(), base),
            "// specialist already carries a launcher, and building on him would produce a",
            "// man with two and no way for the AI to choose. A rifle and the 84 mm slung",
            "// over it is the honest version.",
            "//",
            "// APPEND, NEVER ASSIGN. weapons[] += is the project convention and here it",
            "// is load-bearing: his rifle, magazines and kit are whatever his own faction",
            "// gave him, and this file has no business knowing what they are. Assigning",
            "// weapons[] outright would disarm him of the rifle it did not name.",
            "//",
            "// ONE HE AND ONE AA ROUND, both from futureAmmo:",
            "//   %s    prefragmented HE, programmable airburst" % ROUND_HE,
            "//   %s   VSHORAD IR - helos, low and slow, large UAS" % ROUND_AA,
            "//",
            "// Generated by tools/gen_us_maaws.py - re-run rather than hand-edit.",
            "// The class bodies are bare: config.cpp wraps every piece in ONE",
            "// class CfgVehicles, because four of them is three the engine drops.",
            "",
            "    class %s;" % base,
            "",
            "    class %s: %s {" % (new, base),
            "        scope = 2;",
            "        scopeCurator = 2;",
            "        author = QAUTHOR;",
            '        displayName = "MAAWS Gunner";',
            '        faction = "%s";' % cls,
            "",
            '        weapons[] += {"%s"};' % LAUNCHER,
            '        respawnWeapons[] += {"%s"};' % LAUNCHER,
            '        magazines[] += {"%s", "%s"};' % (ROUND_HE, ROUND_AA),
            '        respawnMagazines[] += {"%s", "%s"};' % (ROUND_HE, ROUND_AA),
            "    };",
        ])

        cfg = os.path.join(d, "config.cpp")
        s = io.open(cfg, encoding="utf-8", newline="").read()
        # config.cpp wraps every piece in ONE class CfgVehicles - a second
        # one is a class the engine drops, taking its contents with it. A
        # piece not listed yet goes INSIDE that block, never ahead of it.
        if '#include "maaws.hpp"' not in s:
            s = s.replace("class CfgVehicles {",
                          'class CfgVehicles {\r\n    #include "maaws.hpp"', 1)

        # The new man is a class this addon adds, so CfgPatches has to say so.
        if new not in s:
            s = s.replace("units[] = {};", 'units[] = {"%s"};' % new)

        io.open(cfg, "w", encoding="utf-8", newline="").write(s)

        print("  %-24s %s  (on %s)" % (comp, new, base))
    return 0


if __name__ == "__main__":
    sys.exit(main())
