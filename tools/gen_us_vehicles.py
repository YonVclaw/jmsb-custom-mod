#!/usr/bin/env python3
"""Give every US Army faction the same vehicle roster.

    python tools/gen_us_vehicles.py

Reads work/factions.json and writes vehicles.hpp into each US Army faction
addon, adding whatever that faction is missing from the COMBINED set the four
of them field between them.

WHY: the four are one army in four theatres. Base US fields 115 vehicles, the
desert roster 70 - so a mission set in the desert quietly loses a third of the
army's equipment, and which vehicles a section can call on depends on the camo
its faction happens to wear. The union fixes that.

DEDUPED BY DISPLAY NAME. Each theatre has its own textured M2A4 Slammer under
its own classname; they are the same vehicle. A faction that already fields one
keeps ITS version - the point is that everybody has an M2A4, not that everybody
has the green one.

THE MARINES ARE NOT IN THIS. MJTF is a different force with its own equipment
list, not a fifth theatre of the US Army. Drones are shared with them because
drone doctrine is shared; tanks are not.
"""
import io
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "work", "factions.json")
ADDONS = os.path.join(ROOT, "addons")

ARMY = [
    ("BLU_F", "faction_blu_f"),
    ("BLU_T_F", "faction_blu_t_f"),
    ("BLU_W_F", "faction_blu_w_f"),
    ("BLU_NATO_lxWS", "faction_blu_nato_lxws"),
]

# Everything that drives, flies, floats or is emplaced. Autonomous is NOT here:
# the drones are their own roster, equalised by tools/gen_us_drones.py, and
# doing both from one union would put Patriot launchers in the drone list.
CATEGORIES = ("Car", "Armored", "Air", "Ship", "Support", "Static", "Submarine")

# The Ram 1500s are removed by remove.hpp in these same addons. Re-adding them
# here under a new classname would undo that in the same PBO.
SKIP_NAMES = ["Ram 1500", "Pickup (AT)"]


def crlf(path, lines):
    io.open(path, "w", encoding="utf-8", newline="\r\n").write("\n".join(lines) + "\n")


def wanted(u):
    if u["vclass"] not in CATEGORIES:
        return False
    return not any(bad.lower() in u["name"].lower() for bad in SKIP_NAMES)


def main():
    if not os.path.isfile(DATA):
        print("no %s" % DATA)
        return 1
    facs = json.load(io.open(DATA, encoding="utf-8"))

    have = {}
    source = {}
    cat = {}
    for cls, comp in ARMY:
        if cls not in facs:
            print("  %s not in the dump - skipped" % cls)
            continue
        veh = [u for u in facs[cls]["units"] if wanted(u)]
        have[cls] = dict((u["name"], u["cls"]) for u in veh)
        for u in veh:
            source.setdefault(u["name"], u["cls"])
            cat.setdefault(u["name"], u["vclass"])

    print("%d distinct vehicle(s) across the four" % len(source))

    for cls, comp in ARMY:
        d = os.path.join(ADDONS, comp)
        if not os.path.isdir(d):
            print("  %-24s MISSING addon - skipped" % comp)
            continue

        mine = have.get(cls, {})
        missing = sorted([n for n in source if n not in mine], key=str.lower)

        lines = [
            "// THE COMBINED VEHICLE ROSTER.",
            "//",
            "// The four US Army factions are one army in four theatres, and they",
            "// shipped very different equipment lists - base US fields 115 vehicles,",
            "// the desert roster 70. A mission set in the desert would quietly lose a",
            "// third of the army's kit, so every theatre gets the union of all four.",
            "//",
            "// THIS FACTION ALREADY HAD %d; %d are added below." % (len(mine), len(missing)),
            "//",
            "// DEDUPED BY DISPLAY NAME. Each theatre has its own textured Slammer under",
            "// its own classname - the point is that every theatre HAS a Slammer, not",
            "// that every theatre has the green one, so a faction that already fields",
            "// one keeps its own.",
            "//",
            "// The Ram 1500s are not here: remove.hpp in this same addon takes them",
            "// out, and re-adding them under a new classname would undo that.",
            "//",
            "// Generated by tools/gen_us_vehicles.py - re-run rather than hand-edit.",
            "// The class bodies are bare: config.cpp wraps every piece in ONE",
            "// class CfgVehicles, because four of them is three the engine drops.",
            "",
        ]

        bases = sorted(set(source[n] for n in missing), key=str.lower)
        for b in bases:
            lines.append("    class %s;" % b)
        if bases:
            lines.append("")

        for n in missing:
            base = source[n]
            new = "jmfsb_%s_%s" % (comp.replace("faction_", ""), base)
            new = re.sub(r"[^A-Za-z0-9_]", "_", new)
            lines += [
                "    class %s: %s {" % (new, base),
                "        scope = 2;",
                "        scopeCurator = 2;",
                "        author = QAUTHOR;",
                '        faction = "%s";' % cls,
                # NO vehicleClass. The base class already carries the right one
                # and re-stating it only creates a second place to be wrong -
                # which is exactly what check_plumbing catches when the value is
                # a category it does not know.
                "    };   // %s" % n,
            ]
        crlf(os.path.join(d, "vehicles.hpp"), lines)

        cfg = os.path.join(d, "config.cpp")
        s = io.open(cfg, encoding="utf-8", newline="").read()
        # config.cpp wraps every piece in ONE class CfgVehicles - a second
        # one is a class the engine drops, taking its contents with it. A
        # piece not listed yet goes INSIDE that block, never ahead of it.
        if '#include "vehicles.hpp"' not in s:
            s = s.replace("class CfgVehicles {",
                          'class CfgVehicles {\r\n    #include "vehicles.hpp"', 1)
        io.open(cfg, "w", encoding="utf-8", newline="").write(s)

        print("  %-24s had %3d, added %3d  -> %d" % (comp, len(mine), len(missing), len(source)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
